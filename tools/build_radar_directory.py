#!/usr/bin/env python3
"""
Build Job Radar's built-in company directory (src/lib/radar-directory.js).

Takes candidate company slugs (tools/radar_candidates.txt, one per line: "slug" or "slug|Display Name"), checks each
against the public Greenhouse, Lever and Ashby job-board APIs, and keeps every board that answers with at least one
open job. Run it again any time to refresh the list:

    python3 tools/build_radar_directory.py            # all candidates
    python3 tools/build_radar_directory.py --limit 50 # quick check

Only public, unauthenticated endpoints are used, a few requests at a time.
"""
import concurrent.futures as cf
import json
import os
import sys
import subprocess
import time

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CANDIDATES = os.path.join(ROOT, 'tools', 'radar_candidates.txt')
OUT = os.path.join(ROOT, 'src', 'lib', 'radar-directory.js')
UA = 'Mozilla/5.0 (job-board directory check)'

BOARDS = {
    'greenhouse': lambda s: f'https://boards-api.greenhouse.io/v1/boards/{s}/jobs?content=false',
    'lever': lambda s: f'https://api.lever.co/v0/postings/{s}?mode=json&limit=1',
    'ashby': lambda s: f'https://api.ashbyhq.com/posting-api/job-board/{s}',
}


def count(board, body):
    try:
        d = json.loads(body)
    except ValueError:
        return 0
    if board == 'greenhouse':
        return len(d.get('jobs') or [])
    if board == 'lever':
        return len(d) if isinstance(d, list) else 0
    if board == 'ashby':
        return len([j for j in (d.get('jobs') or []) if j.get('isListed', True)])
    return 0


def probe(board, slug):
    # curl, not urllib: Python installs on macOS often lack the CA bundle (CERTIFICATE_VERIFY_FAILED).
    try:
        r = subprocess.run(['curl', '-s', '-m', '20', '-A', UA, '-H', 'Accept: application/json', '--max-filesize', '8000000', '-w', '\n%{http_code}', BOARDS[board](slug)], capture_output=True, timeout=30)
        body, _, code = r.stdout.rpartition(b'\n')
        return count(board, body) if code.strip() == b'200' else 0
    except Exception:  # noqa: BLE001 - timeout / no curl: treat as not on this board
        return 0


def main():
    limit = None
    if '--limit' in sys.argv:
        limit = int(sys.argv[sys.argv.index('--limit') + 1])
    rows = []
    for line in open(CANDIDATES, encoding='utf-8'):
        line = line.strip()
        if not line or line.startswith('#'):
            continue
        slug, _, name = line.partition('|')
        rows.append((slug.strip(), (name or slug).strip()))
    rows = rows[:limit] if limit else rows
    found = []
    tasks = [(b, s, n) for s, n in rows for b in BOARDS]
    t0 = time.time()
    with cf.ThreadPoolExecutor(max_workers=8) as ex:
        futs = {ex.submit(probe, b, s): (b, s, n) for b, s, n in tasks}
        for f in cf.as_completed(futs):
            b, s, n = futs[f]
            jobs = f.result()
            if jobs:
                found.append({'board': b, 'company': s, 'name': n, 'jobs': jobs})
    # One board per company name (the one with the most jobs), stable order by name.
    best = {}
    for e in found:
        k = e['name'].lower()
        if k not in best or e['jobs'] > best[k]['jobs']:
            best[k] = e
    out = sorted(best.values(), key=lambda e: e['name'].lower())
    js = '''/*
 * Job Radar built-in company directory: companies whose public Greenhouse, Lever or Ashby job board answered with open
 * jobs when this list was built (%s, %d companies). Generated by tools/build_radar_directory.py — do not edit by hand.
 * Job Radar scans these in rotation (on by default) and shows only the jobs that fit your career tracks.
 */
(function () {
  'use strict';
  const AJP = globalThis.AJP;
  AJP.radar = AJP.radar || {};
  // [board, company id, display name]
  AJP.radar.directory = %s;
})();
''' % (time.strftime('%Y-%m-%d'), len(out), json.dumps([[e['board'], e['company'], e['name']] for e in out], ensure_ascii=False, indent=0).replace('\n', ''))
    open(OUT, 'w', encoding='utf-8').write(js)
    by = {}
    for e in out:
        by[e['board']] = by.get(e['board'], 0) + 1
    print(f'{len(out)} companies ({by}) from {len(rows)} candidates in {time.time() - t0:.0f}s -> {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
